-- Typed system settings: every key declares how its value is validated on save.
--   value_type     STRING | INTEGER | DECIMAL | BOOLEAN | ENUM | PHONE | EMAIL | URL
--   min/max_value  numeric range for INTEGER/DECIMAL; length range for STRING
--   allowed_values comma-separated list for ENUM
--   value_pattern  optional regular expression a STRING value must fully match
--   is_public      exposed without authentication by GET /api/v1/public/site-info
ALTER TABLE system_configurations ADD COLUMN value_type VARCHAR(16) NOT NULL DEFAULT 'STRING';
ALTER TABLE system_configurations ADD COLUMN min_value NUMERIC(20, 4);
ALTER TABLE system_configurations ADD COLUMN max_value NUMERIC(20, 4);
ALTER TABLE system_configurations ADD COLUMN allowed_values VARCHAR(500);
ALTER TABLE system_configurations ADD COLUMN value_pattern VARCHAR(200);
ALTER TABLE system_configurations ADD COLUMN is_public BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE system_configurations ADD CONSTRAINT chk_system_configurations_value_type
    CHECK (value_type IN ('STRING', 'INTEGER', 'DECIMAL', 'BOOLEAN', 'ENUM', 'PHONE', 'EMAIL', 'URL'));

-- Append-only change log; one row per saved change.
CREATE TABLE system_configuration_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key VARCHAR(80) NOT NULL,
    old_value VARCHAR(500),
    new_value VARCHAR(500) NOT NULL,
    changed_by VARCHAR(100),
    changed_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_system_configuration_history_key ON system_configuration_history (config_key, changed_at DESC);

