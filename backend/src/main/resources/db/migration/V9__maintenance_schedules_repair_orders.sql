CREATE TABLE maintenance_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6), updated_at timestamp(6),
    uav_id bigint NOT NULL REFERENCES uavs(id), title varchar(160) NOT NULL,
    interval_days integer NOT NULL CHECK (interval_days BETWEEN 1 AND 3650),
    next_due_date date NOT NULL, last_completed_date date,
    active boolean NOT NULL DEFAULT true, version bigint NOT NULL DEFAULT 0
);
CREATE INDEX ix_maintenance_schedule_uav ON maintenance_schedules(uav_id);
CREATE INDEX ix_maintenance_schedule_due ON maintenance_schedules(active, next_due_date);

CREATE TABLE repair_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6), updated_at timestamp(6),
    uav_id bigint NOT NULL REFERENCES uavs(id), schedule_id bigint REFERENCES maintenance_schedules(id),
    title varchar(160) NOT NULL, description varchar(2000), planned_date date NOT NULL,
    technician_name varchar(120) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('OPEN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    version bigint NOT NULL DEFAULT 0,
    started_at timestamp(6), completed_at timestamp(6), cancelled_at timestamp(6),
    inspection_notes varchar(1000), cancel_reason varchar(1000)
);
CREATE INDEX ix_repair_order_uav ON repair_orders(uav_id);
CREATE INDEX ix_repair_order_schedule ON repair_orders(schedule_id);
CREATE INDEX ix_repair_order_status ON repair_orders(status);
-- The service serializes on uavs; this constraint also protects external database writers.
CREATE UNIQUE INDEX uk_repair_order_active_uav ON repair_orders(uav_id) WHERE status IN ('OPEN', 'IN_PROGRESS');

CREATE TABLE repair_materials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6), updated_at timestamp(6),
    order_id bigint NOT NULL REFERENCES repair_orders(id),
    name varchar(160) NOT NULL, unit varchar(30) NOT NULL,
    quantity numeric(8,3) NOT NULL CHECK (quantity > 0 AND quantity <= 10000),
    unit_price numeric(10,0) NOT NULL CHECK (unit_price >= 0 AND unit_price <= 1000000000)
);
CREATE INDEX ix_repair_material_order ON repair_materials(order_id);
