-- Flyway Migration V4: Search and Rescue (SAR) & AI Detection (YOLOv8s / KV260 Edge)

-- 1. SAR Missions extension
CREATE TABLE sar_missions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id BIGINT NOT NULL UNIQUE REFERENCES missions(id) ON DELETE CASCADE,
    search_area_polygon TEXT NOT NULL,
    lkp_latitude NUMERIC(10, 7) NOT NULL,
    lkp_longitude NUMERIC(10, 7) NOT NULL,
    drift_radius_meters NUMERIC(10, 2) DEFAULT 500.0,
    sar_status VARCHAR(40) NOT NULL DEFAULT 'SEARCHING',
    emergency_contact VARCHAR(100),
    victim_count_estimated INTEGER DEFAULT 1,
    notes VARCHAR(2000),
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

-- 2. AI Tasks Coordination
CREATE TABLE ai_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id BIGINT NOT NULL REFERENCES missions(id) ON DELETE CASCADE,
    media_id BIGINT REFERENCES media_assets(id) ON DELETE SET NULL,
    task_type VARCHAR(50) NOT NULL DEFAULT 'OBJECT_DETECTION_YOLOV8S',
    status VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    processing_node VARCHAR(40) NOT NULL DEFAULT 'KV260_EDGE',
    confidence_threshold NUMERIC(5, 4) DEFAULT 0.75,
    inference_time_ms INTEGER,
    fps NUMERIC(6, 2),
    dpu_utilization NUMERIC(5, 2),
    soc_temperature NUMERIC(5, 2),
    error_message VARCHAR(500),
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP(6)
);

-- 3. AI Detections (Candidate Results)
CREATE TABLE ai_detections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ai_task_id BIGINT NOT NULL REFERENCES ai_tasks(id) ON DELETE CASCADE,
    mission_id BIGINT NOT NULL REFERENCES missions(id) ON DELETE CASCADE,
    label VARCHAR(60) NOT NULL,
    confidence NUMERIC(5, 4) NOT NULL,
    box_top NUMERIC(6, 2) NOT NULL,
    box_left NUMERIC(6, 2) NOT NULL,
    box_width NUMERIC(6, 2) NOT NULL,
    box_height NUMERIC(6, 2) NOT NULL,
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    tracking_id VARCHAR(40),
    verified BOOLEAN NOT NULL DEFAULT false,
    verified_by VARCHAR(100),
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

-- Indexes for performance
CREATE INDEX idx_sar_missions_status ON sar_missions(sar_status);
CREATE INDEX idx_ai_tasks_mission_status ON ai_tasks(mission_id, status);
CREATE INDEX idx_ai_detections_mission ON ai_detections(mission_id);
CREATE INDEX idx_ai_detections_task ON ai_detections(ai_task_id);
