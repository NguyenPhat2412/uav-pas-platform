-- Customer Projects, Project Service Subscriptions, Provider Pilots,
-- and Platform-Mediated Marketplace Order Dispatch columns
-- ==============================================================================

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(180) NOT NULL,
    province VARCHAR(80),
    area_geojson TEXT,
    note VARCHAR(2000),
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_projects_customer_deleted
    ON projects (customer_id, deleted, created_at DESC);

CREATE TABLE project_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    listing_id BIGINT NOT NULL REFERENCES marketplace_listings(id) ON DELETE RESTRICT,
    area_geojson TEXT,
    schedule_type VARCHAR(24) NOT NULL DEFAULT 'ONCE',
    start_date DATE NOT NULL,
    next_run_date DATE,
    units NUMERIC(10, 2) NOT NULL DEFAULT 1,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    note VARCHAR(1000),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_project_subscriptions_project
    ON project_subscriptions (project_id, deleted, created_at DESC);

CREATE INDEX idx_project_subscriptions_customer
    ON project_subscriptions (customer_id, deleted, status);

CREATE TABLE provider_pilots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL REFERENCES provider_profiles(id) ON DELETE CASCADE,
    pilot_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    assigned_uav_id BIGINT REFERENCES uavs(id) ON DELETE SET NULL,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(160),
    phone VARCHAR(30),
    license_number VARCHAR(80),
    specialization VARCHAR(120),
    pilot_status VARCHAR(24) NOT NULL DEFAULT 'AVAILABLE',
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_provider_pilots_provider
    ON provider_pilots (provider_id, deleted, created_at DESC);

ALTER TABLE missions ADD COLUMN IF NOT EXISTS project_id BIGINT REFERENCES projects(id) ON DELETE SET NULL;
ALTER TABLE missions ADD COLUMN IF NOT EXISTS subscription_id BIGINT REFERENCES project_subscriptions(id) ON DELETE SET NULL;
ALTER TABLE marketplace_listings ADD COLUMN IF NOT EXISTS deleted BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS idx_missions_project ON missions (project_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_missions_subscription ON missions (subscription_id);
