-- 2. User Quotas
CREATE TABLE user_quotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    plan_id BIGINT NOT NULL REFERENCES service_plans(id),
    flight_hours_used NUMERIC(8, 2) NOT NULL DEFAULT 0.0,
    flight_hours_limit NUMERIC(8, 2) NOT NULL DEFAULT 20.0,
    concurrent_uavs_used INTEGER NOT NULL DEFAULT 0,
    concurrent_uavs_limit INTEGER NOT NULL DEFAULT 1,
    cycle_start TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    cycle_end TIMESTAMP(6),
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

-- 3. Invoices
CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    mission_id BIGINT REFERENCES missions(id) ON DELETE SET NULL,
    plan_id BIGINT REFERENCES service_plans(id) ON DELETE SET NULL,
    amount NUMERIC(14, 2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    due_date TIMESTAMP(6) NOT NULL,
    paid_at TIMESTAMP(6),
    notes VARCHAR(500),
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

-- 4. Payment Transactions
CREATE TABLE payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    transaction_code VARCHAR(100) NOT NULL UNIQUE,
    gateway_name VARCHAR(50) NOT NULL DEFAULT 'VIETQR_NAPAS',
    amount NUMERIC(15, 2) NOT NULL,
    bank_bin VARCHAR(20) DEFAULT '970415',
    bank_account_number VARCHAR(50) DEFAULT '101869876543',
    emvco_payload TEXT,
    raw_ipn_callback TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP(6)
);

CREATE INDEX idx_user_quotas_user ON user_quotas(user_id);
CREATE INDEX idx_invoices_user_status ON invoices(user_id, status);
CREATE INDEX idx_invoices_code ON invoices(code);
CREATE INDEX idx_payment_tx_invoice ON payment_transactions(invoice_id);
