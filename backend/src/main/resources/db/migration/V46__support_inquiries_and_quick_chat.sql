CREATE TABLE support_threads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    visitor_token VARCHAR(96) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    organization VARCHAR(160),
    contact_info VARCHAR(160) NOT NULL,
    topic VARCHAR(40) NOT NULL DEFAULT 'SURVEY_SERVICE',
    source VARCHAR(24) NOT NULL DEFAULT 'LIVE_WIDGET',
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
    unread_for_admin INT NOT NULL DEFAULT 1,
    unread_for_visitor INT NOT NULL DEFAULT 0,
    last_message_preview VARCHAR(280),
    last_sender_role VARCHAR(16) NOT NULL DEFAULT 'VISITOR',
    assigned_admin_username VARCHAR(100),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_support_threads_status_updated
    ON support_threads (status, updated_at DESC);

CREATE INDEX idx_support_threads_unread_admin_updated
    ON support_threads (unread_for_admin, updated_at DESC);

CREATE TABLE support_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT NOT NULL REFERENCES support_threads(id) ON DELETE CASCADE,
    sender_role VARCHAR(16) NOT NULL,
    sender_name VARCHAR(120) NOT NULL,
    content VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_support_messages_thread_created
    ON support_messages (thread_id, created_at ASC);

CREATE TABLE support_quick_replies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    topic VARCHAR(40),
    content VARCHAR(2000) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_by VARCHAR(100),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_support_quick_replies_sort
    ON support_quick_replies (sort_order ASC, id ASC);

