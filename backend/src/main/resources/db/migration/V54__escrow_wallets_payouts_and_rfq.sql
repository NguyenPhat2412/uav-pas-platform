ALTER TABLE invoices ADD COLUMN provider_id BIGINT REFERENCES provider_profiles(id) ON DELETE SET NULL;
ALTER TABLE invoices ADD COLUMN escrow_status VARCHAR(24) NOT NULL DEFAULT 'NONE';
ALTER TABLE invoices ADD COLUMN platform_fee_rate NUMERIC(5, 4);
ALTER TABLE invoices ADD COLUMN platform_fee_vnd NUMERIC(14, 2);
ALTER TABLE invoices ADD COLUMN provider_net_vnd NUMERIC(14, 2);
ALTER TABLE invoices ADD COLUMN escrow_released_at TIMESTAMP(6);

CREATE INDEX idx_invoices_provider_escrow
    ON invoices (provider_id, escrow_status, created_at DESC);

CREATE TABLE provider_wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL UNIQUE REFERENCES provider_profiles(id) ON DELETE CASCADE,
    escrow_held_vnd NUMERIC(14, 2) NOT NULL DEFAULT 0,
    available_balance_vnd NUMERIC(14, 2) NOT NULL DEFAULT 0,
    pending_payout_vnd NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_earned_vnd NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_withdrawn_vnd NUMERIC(14, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE provider_payouts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    provider_id BIGINT NOT NULL REFERENCES provider_profiles(id) ON DELETE CASCADE,
    amount_vnd NUMERIC(14, 2) NOT NULL,
    bank_name VARCHAR(120) NOT NULL,
    bank_account_number VARCHAR(60) NOT NULL,
    bank_account_holder VARCHAR(120) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    provider_note VARCHAR(500),
    admin_note VARCHAR(500),
    bank_transfer_ref VARCHAR(120),
    processed_by VARCHAR(100),
    processed_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_provider_payouts_status
    ON provider_payouts (status, created_at DESC);

CREATE INDEX idx_provider_payouts_provider
    ON provider_payouts (provider_id, created_at DESC);

CREATE TABLE wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT NOT NULL REFERENCES provider_wallets(id) ON DELETE CASCADE,
    invoice_id BIGINT REFERENCES invoices(id) ON DELETE SET NULL,
    payout_id BIGINT REFERENCES provider_payouts(id) ON DELETE SET NULL,
    transaction_type VARCHAR(30) NOT NULL,
    gross_amount_vnd NUMERIC(14, 2) NOT NULL,
    fee_amount_vnd NUMERIC(14, 2) NOT NULL DEFAULT 0,
    net_amount_vnd NUMERIC(14, 2) NOT NULL,
    balance_after_vnd NUMERIC(14, 2) NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_wallet_transactions_wallet
    ON wallet_transactions (wallet_id, created_at DESC);

CREATE TABLE mission_bids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id BIGINT NOT NULL REFERENCES missions(id) ON DELETE CASCADE,
    provider_id BIGINT NOT NULL REFERENCES provider_profiles(id) ON DELETE CASCADE,
    proposed_price_vnd NUMERIC(14, 2) NOT NULL,
    estimated_delivery_hours INT,
    proposal_note VARCHAR(1500),
    proposed_uav_model VARCHAR(120),
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    responded_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_mission_bids_mission_provider UNIQUE (mission_id, provider_id)
);

CREATE INDEX idx_mission_bids_mission
    ON mission_bids (mission_id, status, proposed_price_vnd ASC);

CREATE INDEX idx_mission_bids_provider
    ON mission_bids (provider_id, created_at DESC);

