-- Weather & flight-safety intelligence.
--   weather_provider_settings  one row (id = 1): data source, the optional provider API key
--                              (AES-256-GCM, never returned by the API), cache lifetime and
--                              whether a NO_GO assessment blocks a mission start.
--   weather_observations_cache forecasts per ~1.1 km grid cell (coordinates rounded to 2 decimals)
--                              and local target hour; payload_json holds the hourly series from
--                              that hour so recommended flight windows need no second request.

CREATE TABLE weather_provider_settings (
    id INTEGER PRIMARY KEY,
    provider VARCHAR(30) NOT NULL DEFAULT 'OPEN_METEO',
    api_key_cipher TEXT,
    cache_ttl_minutes INTEGER NOT NULL DEFAULT 30,
    enforce_preflight_block BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP(6),
    updated_by VARCHAR(100),
    CONSTRAINT chk_weather_provider_settings_single_row CHECK (id = 1),
    CONSTRAINT chk_weather_provider_settings_provider CHECK (provider IN ('OPEN_METEO', 'OPENWEATHERMAP')),
    CONSTRAINT chk_weather_provider_settings_ttl CHECK (cache_ttl_minutes BETWEEN 1 AND 120)
);

INSERT INTO weather_provider_settings (id, provider, cache_ttl_minutes, enforce_preflight_block, updated_at, updated_by)
VALUES (1, 'OPEN_METEO', 30, FALSE, CURRENT_TIMESTAMP, 'SYSTEM');

CREATE TABLE weather_observations_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    grid_lat DOUBLE PRECISION NOT NULL,
    grid_lng DOUBLE PRECISION NOT NULL,
    target_hour VARCHAR(16) NOT NULL,
    provider VARCHAR(30) NOT NULL,
    payload_json TEXT NOT NULL,
    kp_index DOUBLE PRECISION,
    fetched_at TIMESTAMP(6) NOT NULL
);

CREATE UNIQUE INDEX ux_weather_observations_cache_cell
    ON weather_observations_cache (grid_lat, grid_lng, target_hour, provider);
CREATE INDEX idx_weather_observations_cache_fetched ON weather_observations_cache (fetched_at);

