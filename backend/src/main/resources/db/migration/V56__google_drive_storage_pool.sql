CREATE TABLE storage_drive_nodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) NOT NULL UNIQUE,
    display_name VARCHAR(140) NOT NULL,
    auth_type VARCHAR(24) NOT NULL DEFAULT 'OAUTH2',
    account_email VARCHAR(180),
    encrypted_credentials TEXT NOT NULL,
    root_folder_id VARCHAR(160),
    folder_cache_json TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    priority_weight INT NOT NULL DEFAULT 100,
    max_usage_percent INT NOT NULL DEFAULT 92,
    routed_modules VARCHAR(300) NOT NULL DEFAULT 'ALL',
    quota_limit_bytes BIGINT,
    quota_used_bytes BIGINT,
    quota_drive_bytes BIGINT,
    health_status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    last_error VARCHAR(240),
    last_checked_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_storage_drive_nodes_enabled
    ON storage_drive_nodes (enabled, priority_weight DESC, id ASC);

CREATE TABLE storage_drive_objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_key VARCHAR(500) NOT NULL UNIQUE,
    node_id BIGINT NOT NULL REFERENCES storage_drive_nodes(id) ON DELETE RESTRICT,
    drive_file_id VARCHAR(160) NOT NULL,
    drive_folder_id VARCHAR(160),
    module_folder VARCHAR(60),
    file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(120) NOT NULL,
    size_bytes BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_storage_drive_objects_node
    ON storage_drive_objects (node_id, created_at DESC);

