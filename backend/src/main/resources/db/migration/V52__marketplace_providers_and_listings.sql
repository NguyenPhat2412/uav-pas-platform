INSERT INTO permissions (code, description, created_at, updated_at)
SELECT 'MARKETPLACE_MODERATE', 'MARKETPLACE_MODERATE', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
WHERE NOT EXISTS (SELECT 1 FROM permissions WHERE code = 'MARKETPLACE_MODERATE');

INSERT INTO permissions (code, description, created_at, updated_at)
SELECT 'PAYOUT_MANAGE', 'PAYOUT_MANAGE', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
WHERE NOT EXISTS (SELECT 1 FROM permissions WHERE code = 'PAYOUT_MANAGE');

INSERT INTO role_template_permissions (role_template_id, permission_id, created_at, updated_at)
SELECT t.id, p.id, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM role_templates t
JOIN permissions p ON p.code = 'MARKETPLACE_MODERATE'
WHERE t.role IN ('ROLE_ADMIN', 'ROLE_COMMANDER')
  AND t.defaults_initialized = TRUE
  AND NOT EXISTS (
      SELECT 1 FROM role_template_permissions x
      WHERE x.role_template_id = t.id AND x.permission_id = p.id);

INSERT INTO role_template_permissions (role_template_id, permission_id, created_at, updated_at)
SELECT t.id, p.id, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM role_templates t
JOIN permissions p ON p.code = 'PAYOUT_MANAGE'
WHERE t.role = 'ROLE_ADMIN'
  AND t.defaults_initialized = TRUE
  AND NOT EXISTS (
      SELECT 1 FROM role_template_permissions x
      WHERE x.role_template_id = t.id AND x.permission_id = p.id);

CREATE TABLE provider_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    display_name VARCHAR(160) NOT NULL,
    provider_type VARCHAR(24) NOT NULL DEFAULT 'INDIVIDUAL',
    tax_or_id_number VARCHAR(60),
    flight_license_number VARCHAR(80),
    bio VARCHAR(2000),
    province VARCHAR(80),
    service_radius_km INT NOT NULL DEFAULT 50,
    contact_phone VARCHAR(30),
    bank_name VARCHAR(120),
    bank_account_number VARCHAR(60),
    bank_account_holder VARCHAR(120),
    verification_status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    review_note VARCHAR(1000),
    verified_at TIMESTAMP(6),
    verified_by VARCHAR(100),
    commission_rate_override NUMERIC(5, 4),
    rating_avg NUMERIC(3, 2) NOT NULL DEFAULT 0,
    review_count INT NOT NULL DEFAULT 0,
    completed_missions_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_provider_profiles_status_province
    ON provider_profiles (verification_status, province);

CREATE TABLE provider_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL REFERENCES provider_profiles(id) ON DELETE CASCADE,
    document_type VARCHAR(40) NOT NULL,
    title VARCHAR(160) NOT NULL,
    document_number VARCHAR(80),
    file_url VARCHAR(500),
    media_asset_id BIGINT REFERENCES media_assets(id) ON DELETE SET NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    reviewer_note VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_provider_documents_provider
    ON provider_documents (provider_id, created_at DESC);

CREATE TABLE marketplace_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT REFERENCES provider_profiles(id) ON DELETE CASCADE,
    category_service_id BIGINT REFERENCES uav_services(id) ON DELETE SET NULL,
    slug VARCHAR(160) NOT NULL UNIQUE,
    title VARCHAR(180) NOT NULL,
    summary VARCHAR(500),
    description VARCHAR(4000),
    listing_type VARCHAR(30) NOT NULL DEFAULT 'FLIGHT_SERVICE',
    mission_type VARCHAR(30) NOT NULL DEFAULT 'AREA_INSPECTION',
    pricing_model VARCHAR(30) NOT NULL DEFAULT 'PER_HOUR',
    base_price_vnd NUMERIC(14, 2) NOT NULL,
    min_booking_units NUMERIC(10, 2) NOT NULL DEFAULT 1,
    security_deposit_vnd NUMERIC(14, 2) NOT NULL DEFAULT 0,
    province VARCHAR(80),
    service_radius_km INT NOT NULL DEFAULT 100,
    equipment_specs VARCHAR(1000),
    deliverables_summary VARCHAR(1000),
    cover_image_url VARCHAR(500),
    on_site_sla_hours INT,
    delivery_sla_hours INT,
    moderation_status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    moderation_note VARCHAR(1000),
    moderated_by VARCHAR(100),
    moderated_at TIMESTAMP(6),
    rating_avg NUMERIC(3, 2) NOT NULL DEFAULT 0,
    review_count INT NOT NULL DEFAULT 0,
    booking_count INT NOT NULL DEFAULT 0,
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_marketplace_listings_public
    ON marketplace_listings (moderation_status, listing_type, province, featured DESC, created_at DESC);

CREATE INDEX idx_marketplace_listings_provider
    ON marketplace_listings (provider_id, created_at DESC);

ALTER TABLE uavs ADD COLUMN provider_id BIGINT REFERENCES provider_profiles(id) ON DELETE SET NULL;
ALTER TABLE uav_stations ADD COLUMN provider_id BIGINT REFERENCES provider_profiles(id) ON DELETE SET NULL;
ALTER TABLE equipment ADD COLUMN provider_id BIGINT REFERENCES provider_profiles(id) ON DELETE SET NULL;

CREATE INDEX idx_uavs_provider ON uavs (provider_id);
CREATE INDEX idx_stations_provider ON uav_stations (provider_id);
CREATE INDEX idx_equipment_provider ON equipment (provider_id);

