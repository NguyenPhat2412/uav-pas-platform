INSERT INTO marketplace_listings (
    provider_id,
    category_service_id,
    slug,
    title,
    summary,
    description,
    listing_type,
    mission_type,
    pricing_model,
    base_price_vnd,
    min_booking_units,
    security_deposit_vnd,
    province,
    service_radius_km,
    equipment_specs,
    deliverables_summary,
    on_site_sla_hours,
    delivery_sla_hours,
    moderation_status,
    moderated_by,
    moderated_at,
    featured
)
SELECT
    NULL,
    s.id,
    LOWER(REPLACE(s.code, '_', '-')) || '-official',
    s.name || ' (Đội bay Chính hãng UAV-PAS)',
    COALESCE(s.description, 'Dịch vụ bay khảo sát và vận hành UAV tiêu chuẩn an toàn hàng không do đội ngũ kỹ thuật UAV-PAS trực tiếp triển khai.'),
    COALESCE(s.description, '') || ' Triển khai trọn gói bao gồm thẩm định không phận NFZ/NOTAM, kiểm tra khí tượng trước cất cánh, vận hành bởi tổ lái chứng chỉ và bàn giao dữ liệu gốc qua kho lưu trữ bảo mật.',
    CASE WHEN s.code = 'UAV_RENTAL' THEN 'WET_LEASE' ELSE 'FLIGHT_SERVICE' END,
    CASE
        WHEN s.code IN ('UAV_RENTAL', 'AREA_INSPECTION', 'AERIAL_RECORDING', 'DATA_COLLECTION') THEN s.code
        ELSE 'OTHER'
    END,
    CASE WHEN s.code = 'DATA_COLLECTION' THEN 'PER_HECTARE' ELSE 'PER_HOUR' END,
    CASE
        WHEN s.code = 'UAV_RENTAL' THEN 2500000
        WHEN s.code = 'AREA_INSPECTION' THEN 3200000
        WHEN s.code = 'AERIAL_RECORDING' THEN 2800000
        WHEN s.code = 'DATA_COLLECTION' THEN 450000
        ELSE 2500000
    END,
    CASE WHEN s.code = 'DATA_COLLECTION' THEN 10 ELSE 2 END,
    0,
    'Toàn quốc',
    500,
    COALESCE('Cảm biến hỗ trợ: ' || s.sensors, 'DJI Matrice 350 RTK / Mavic 3 Enterprise RTK'),
    'Bình đồ trực giao GeoTIFF, ảnh gốc gắn tọa độ RTK, báo cáo nghiệm thu kỹ thuật PDF',
    COALESCE(s.on_site_hours, 24),
    COALESCE(s.delivery_hours, 48),
    'PUBLISHED',
    'SYSTEM',
    CURRENT_TIMESTAMP,
    TRUE
FROM uav_services s
WHERE s.active = TRUE
  AND NOT EXISTS (
      SELECT 1 FROM marketplace_listings m
      WHERE m.slug = LOWER(REPLACE(s.code, '_', '-')) || '-official'
  );
