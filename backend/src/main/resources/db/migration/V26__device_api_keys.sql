-- Machine credentials for ground stations / UAV gateways that push telemetry.
-- Only the SHA-256 hex digest of the full key is stored; the key itself is shown once at creation.
-- key_prefix is a short, non-secret fragment so operators can recognise a key in the list.
CREATE TABLE device_api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    uav_id BIGINT REFERENCES uavs(id),
    key_prefix VARCHAR(16) NOT NULL,
    key_hash VARCHAR(64) NOT NULL,
    scopes TEXT NOT NULL DEFAULT 'TELEMETRY_WRITE',
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMP(6),
    expires_at TIMESTAMP(6),
    revoked_at TIMESTAMP(6),
    CONSTRAINT uk_device_api_keys_hash UNIQUE (key_hash)
);

CREATE INDEX idx_device_api_keys_uav ON device_api_keys (uav_id);
CREATE INDEX idx_device_api_keys_expiry ON device_api_keys (expires_at) WHERE revoked_at IS NULL;
