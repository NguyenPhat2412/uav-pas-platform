#!/usr/bin/env node
// Copies the web app's platform-neutral modules (DTO types, pure forms, API routes, formatters, weather rules,
// message catalogs) into src/shared/, so the iPhone app speaks the same contracts as frontend/ without importing
// across projects. Every `@/x` import inside a copied file becomes `@/shared/x`, and the import closure is followed
// automatically. A copied file may only import other copied files or an allowed package; anything touching the DOM,
// Next.js or a web-only library stops the sync with the offending path.
//
//   npm run sync:shared          rewrite src/shared/ from ../frontend/src
//   npm run sync:shared -- --check   fail (exit 1) when src/shared/ is out of date (used by the tests)

import {existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const mobileRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const webSrc = join(mobileRoot, '..', 'frontend', 'src');
const outDir = join(mobileRoot, 'src', 'shared');

/** Entry points (files or folders, relative to frontend/src); their imports are pulled in automatically. */
export const ROOTS = [
    'types/assistant/assistant.types.ts',
    'types/auth/auth.types.ts',
    'types/customer.ts',
    'types/billing/billing.types.ts',
    'types/catalog',
    'types/dashboard',
    'types/notification',
    'types/profile',
    'types/training',
    'types/weather',
    'forms/auth',
    'forms/mission/mission-form.ts',
    'forms/profile',
    'lib/api/routes.ts',
    'lib/api/messages.ts',
    'lib/format.ts',
    'lib/query',
    'hooks/assistant/query-keys.ts',
    'hooks/billing/query-keys.ts',
    'hooks/dashboard/query-keys.ts',
    'hooks/media/query-keys.ts',
    'hooks/profile/query-keys.ts',
    'hooks/training/query-keys.ts',
    'hooks/weather/query-keys.ts',
    'utils/auth/portal.ts',
    'lib/presentation.ts',
    'i18n/config.ts',
    'utils/training/course-helpers.ts',
    'utils/weather/conditions.ts',
    'utils/weather/sky-theme.ts',
    'utils/weather/flight-window.ts',
    'utils/errors/runtime-error.ts',
    'messages/vi.json',
    'messages/en.json',
    'messages/ja.json',
    'messages/customer',
    'messages/sections/customerPro',
    // The assistant's texts (admin.assistant.*) live in the admin section on the web too.
    'messages/sections/admin',
];

/** Web-only modules left out on purpose; lines that import or re-export them are dropped from the copies. */
export const OMIT = ['types/ui.ts'];

/** The only packages a shared module may import (both apps install them). */
export const ALLOWED_PACKAGES = ['zod', '@tanstack/react-query'];

const BROWSER_GLOBALS = /\b(?:window|document|localStorage|sessionStorage|navigator)\s*\./;
const IMPORT = /(?:import|export)\s+(?:type\s+)?(?:[^'";]*?\s+from\s+)?['"]([^'"]+)['"]/g;
const HEADER = rel => `// Generated by mobile/scripts/sync-shared.mjs from frontend/src/${rel}. Do not edit here:\n` +
    `// change the web file, then run \`npm run sync:shared\` in mobile/.\n`;

function walk(rel) {
    const abs = join(webSrc, rel);
    if (!existsSync(abs)) throw new Error(`sync-shared: root not found: frontend/src/${rel}`);
    if (!statSync(abs).isDirectory()) return [rel];
    return readdirSync(abs).flatMap(name => walk(join(rel, name)))
        .filter(file => /\.(ts|json)$/.test(file) && !/\.(test|spec)\./.test(file));
}

function resolveAlias(spec) {
    const base = spec.slice(2);
    for (const candidate of [`${base}.ts`, `${base}/index.ts`, base])
        if (existsSync(join(webSrc, candidate)) && statSync(join(webSrc, candidate)).isFile()) return candidate;
    throw new Error(`sync-shared: cannot resolve ${spec}`);
}

function resolveRelative(fromRel, spec) {
    return resolveAlias(`@/${join(dirname(fromRel), spec)}`);
}

const omitted = new Set(OMIT);

function isOmitted(spec, fromRel) {
    if (spec.startsWith('@/')) return omitted.has(resolveAlias(spec));
    if (spec.startsWith('.')) return omitted.has(resolveRelative(fromRel, spec));
    return false;
}

/** Copies (rewritten) by path, plus the reason a module cannot be shared. */
export function build() {
    const queue = ROOTS.flatMap(walk);
    const files = new Map();
    const problems = [];
    while (queue.length) {
        const rel = queue.shift();
        if (files.has(rel) || omitted.has(rel)) continue;
        const source = readFileSync(join(webSrc, rel), 'utf8');
        if (rel.endsWith('.json')) {
            files.set(rel, source);
            continue;
        }
        const kept = source.split('\n').filter(line => {
            const spec = /from\s+['"]([^'"]+)['"]/.exec(line)?.[1];
            return !(spec && isOmitted(spec, rel));
        }).join('\n');
        const code = kept.replace(/\/\*[\s\S]*?\*\/|\/\/.*$/gm, '');
        if (BROWSER_GLOBALS.test(code)) problems.push(`${rel}: uses a browser global`);
        for (const [, spec] of kept.matchAll(IMPORT)) {
            if (spec.startsWith('@/')) queue.push(resolveAlias(spec));
            else if (spec.startsWith('.')) queue.push(resolveRelative(rel, spec));
            else if (!ALLOWED_PACKAGES.includes(spec)) problems.push(`${rel}: imports '${spec}'`);
        }
        files.set(rel, HEADER(rel) + kept.replace(/(['"])@\/(?!shared\/)/g, '$1@/shared/'));
    }
    return {files, problems};
}

function listExisting(dir, prefix = '') {
    if (!existsSync(dir)) return [];
    return readdirSync(dir).flatMap(name => {
        const abs = join(dir, name);
        const rel = prefix ? `${prefix}/${name}` : name;
        return statSync(abs).isDirectory() ? listExisting(abs, rel) : [rel];
    }).filter(rel => rel !== 'README.md');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
    const {files, problems} = build();
    if (problems.length) {
        console.error('sync-shared: these modules are not platform-neutral:\n  ' + problems.join('\n  '));
        process.exit(1);
    }
    if (process.argv.includes('--check')) {
        const stale = [...files].filter(([rel, text]) => !existsSync(join(outDir, rel)) || readFileSync(join(outDir, rel), 'utf8') !== text)
            .map(([rel]) => rel);
        const extra = listExisting(outDir).filter(rel => !files.has(rel));
        if (stale.length || extra.length) {
            console.error(`sync-shared: src/shared is out of date; run \`npm run sync:shared\`.\n  ${[...stale, ...extra].join('\n  ')}`);
            process.exit(1);
        }
        console.log(`sync-shared: ${files.size} shared files up to date`);
    } else {
        for (const rel of listExisting(outDir)) if (!files.has(rel)) rmSync(join(outDir, rel));
        for (const [rel, text] of files) {
            mkdirSync(dirname(join(outDir, rel)), {recursive: true});
            writeFileSync(join(outDir, rel), text);
        }
        console.log(`sync-shared: wrote ${files.size} files to ${relative(mobileRoot, outDir)}`);
    }
}
