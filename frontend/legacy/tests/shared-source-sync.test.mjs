import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';

test('legacy generated upload policy stays byte-identical to the shared policy', async () => {
  const shared = await readFile(new URL('../../packages/api-client/src/media-policy.ts', import.meta.url), 'utf8');
  const generated = await readFile(new URL('../src/lib/media-policy.ts', import.meta.url), 'utf8');
  assert.equal(generated, '/* Generated by scripts/sync-portal-theme.mjs. Edit frontend/packages instead. */\n' + shared);
});
